// Rebuilds src/endpoints.ts, src/generated.ts and docs/endpoints.md from the public OpenAPI file.
//
//   node scripts/generate.mjs              downloads https://dataporium.tech/openapi.json
//   node scripts/generate.mjs spec.json    uses a local copy
import { readFile, writeFile } from "node:fs/promises";

const SPEC_URL = "https://dataporium.tech/openapi.json";
const root = new URL("..", import.meta.url);

const spec = process.argv[2]
  ? JSON.parse(await readFile(process.argv[2], "utf8"))
  : await (await fetch(SPEC_URL)).json();

const clean = (text) => (text ?? "").replace(/\s+/g, " ").trim();
const camel = (name) => name.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
const isIdent = (name) => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name);
const key = (name) => (isIdent(name) ? name : JSON.stringify(name));
const comment = (text) => text.replace(/\*\//g, "*\\/");

const endpoints = [];
for (const [path, ops] of Object.entries(spec.paths)) {
  const op = ops.get;
  if (!op) continue;
  endpoints.push({
    name: op.operationId,
    method: camel(op.operationId),
    path,
    summary: clean(op.summary),
    description: clean(op.description),
    category: (op.tags ?? ["Other"])[0],
    params: (op.parameters ?? []).map((p) => ({
      name: p.name,
      in: p.in ?? "query",
      description: clean(p.description),
      ...(p.example !== undefined ? { example: p.example } : {}),
    })),
  });
}

const banner = "// This file is generated by scripts/generate.mjs from " + SPEC_URL + ". Do not edit it by hand.\n";

// src/endpoints.ts
const data = Object.fromEntries(endpoints.map((e) => [e.method, {
  name: e.name, path: e.path, summary: e.summary, description: e.description, category: e.category, params: e.params,
}]));
await writeFile(new URL("src/endpoints.ts", root),
  banner +
  'import type { Endpoint } from "./types.js";\n\n' +
  "export const API_VERSION = " + JSON.stringify(spec.info?.version ?? "") + ";\n\n" +
  "export const ENDPOINTS: Readonly<Record<string, Endpoint>> = " + JSON.stringify(data, null, 1) + ";\n");

// src/generated.ts
const lines = [
  banner,
  'import type { QueryValue } from "./types.js";',
  "",
  "/** One typed method per endpoint of the DataPorium Data API. */",
  "export abstract class DataPoriumEndpoints {",
  "  /** Calls an endpoint by its method name. */",
  "  abstract call(method: string, params?: Record<string, QueryValue | undefined>): Promise<any>;",
];
for (const e of endpoints) {
  const pathParams = e.params.filter((p) => p.in === "path");
  const fields = e.params.map((p) => {
    const doc = p.description || p.example !== undefined
      ? `    /** ${comment(p.description)}${p.example !== undefined ? ` Example: ${comment(String(p.example))}` : ""} */\n`
      : "";
    return `${doc}    ${key(p.name)}${p.in === "path" ? "" : "?"}: QueryValue;`;
  });
  const type = fields.length ? `{\n${fields.join("\n")}\n  }` : "Record<string, never>";
  const optional = pathParams.length ? "" : "?";
  lines.push("");
  lines.push("  /**");
  lines.push(`   * ${comment(e.summary)} (${e.category}). GET ${e.path}`);
  if (e.description) lines.push(`   *`, `   * ${comment(e.description)}`);
  lines.push("   */");
  lines.push(`  ${e.method}(params${optional}: ${type}): Promise<any> {`);
  lines.push(`    return this.call(${JSON.stringify(e.method)}, params);`);
  lines.push("  }");
}
lines.push("}", "");
await writeFile(new URL("src/generated.ts", root), lines.join("\n"));

// docs/endpoints.md
const byCategory = new Map();
for (const e of endpoints) {
  if (!byCategory.has(e.category)) byCategory.set(e.category, []);
  byCategory.get(e.category).push(e);
}
const anchor = (c) => c.toLowerCase().replace(/ /g, "-").replace(/[^a-z0-9-]/g, "");
const md = [
  "# Endpoint reference",
  "",
  `All ${endpoints.length} endpoints of the DataPorium Data API, grouped by category. Each one is a method on the client with the name shown, for example \`await dp.companyInfo({ symbol: "AAPL" })\`.`,
  "",
  `This page is generated from the public OpenAPI file at <${SPEC_URL}>. For parameter details and example answers see the [API documentation](https://dataporium.tech/api-docs), or print \`dp.describe("<method name>")\`. Parameter names are the API's own, so they stay in snake_case.`,
  "",
  "## Categories",
  "",
  ...[...byCategory].map(([c, list]) => `- [${c}](#${anchor(c)}) (${list.length})`),
];
for (const [c, list] of byCategory) {
  md.push("", `## ${c}`, "", "| Method | Path | What it returns |", "|---|---|---|");
  for (const e of list) md.push(`| \`${e.method}\` | \`${e.path}\` | ${e.summary} |`);
}
await writeFile(new URL("docs/endpoints.md", root), md.join("\n") + "\n");

console.log(`${endpoints.length} endpoints written to src/endpoints.ts, src/generated.ts and docs/endpoints.md`);
